import { posix } from 'node:path'
import type {
  ClientManifestValue,
  DiscoveredDefinition,
  GeneratedPanelArtifact,
} from '../discovery/types'

const GENERATED_HEADER = '// Generated by holo prepare. Do not edit.'

const artifactNames = [
  'panels.ts',
  'server-registry.ts',
  'client-manifest.ts',
  'client-components.ts',
  'resources.ts',
  'pages.ts',
  'widgets.ts',
  'clusters.ts',
  'navigation.ts',
  'permissions.ts',
  'types.d.ts',
  'framework-artifacts.json',
  'panel-routes.json',
  'registry.json',
] as const

function renderModule(exportName: string, value: ClientManifestValue): string {
  return `${GENERATED_HEADER}\n\nexport const ${exportName} = ${JSON.stringify(value, null, 2)} as const\n\nexport default ${exportName}\n`
}

function registryValue(definitions: readonly DiscoveredDefinition[]): ClientManifestValue {
  return {
    version: 1,
    definitions: definitions.map(definition => ({
      kind: definition.kind,
      id: definition.id,
      panelId: definition.panelId,
      projectPath: definition.projectPath,
      exportName: definition.exportName,
      ...(definition.route ? { route: definition.route } : {}),
      permissionKeys: definition.permissionKeys,
      componentKeys: definition.componentKeys,
      navigationKeys: definition.navigationKeys,
      default: definition.default,
      client: definition.client,
    })),
  }
}

function publicValue(definition: DiscoveredDefinition): ClientManifestValue {
  return {
    kind: definition.kind,
    id: definition.id,
    panelId: definition.panelId,
    ...(definition.route ? { route: definition.route } : {}),
    ...definition.client,
  }
}

function byKind(
  definitions: readonly DiscoveredDefinition[],
  kind: DiscoveredDefinition['kind'],
): ClientManifestValue {
  return definitions.filter(definition => definition.kind === kind).map(publicValue)
}

function renderServerRegistry(definitions: readonly DiscoveredDefinition[]): string {
  const entries = definitions.map((definition) => {
    const importPath = posix.join('../../..', definition.projectPath).replace(/\.[cm]?[jt]sx?$/, '')
    if (definition.generatedResourcePage) {
      return `  ${JSON.stringify(`${definition.panelId}:${definition.kind}:${definition.id}`)}: async () => { const { createGeneratedResourcePage } = await import('@holo-js/panels/server'); const resource = (await import(${JSON.stringify(importPath)}))[${JSON.stringify(definition.generatedResourcePage.resourceExportName)}]; return createGeneratedResourcePage(resource, ${JSON.stringify(definition.generatedResourcePage.manifest)}) },`
    }
    if (definition.registeredFrom) {
      return `  ${JSON.stringify(`${definition.panelId}:${definition.kind}:${definition.id}`)}: async () => { const panel = (await import(${JSON.stringify(importPath)}))[${JSON.stringify(definition.registeredFrom.exportName)}]; const definition = 'compileDiscoveryDefinition' in panel ? panel.compileDiscoveryDefinition() : panel; return definition.server.registered[${definition.registeredFrom.index}].value },`
    }
    return `  ${JSON.stringify(`${definition.panelId}:${definition.kind}:${definition.id}`)}: async () => (await import(${JSON.stringify(importPath)}))[${JSON.stringify(definition.exportName)}],`
  })

  return [
    GENERATED_HEADER,
    '',
    'export const serverRegistry = {',
    ...entries,
    '} as const',
    '',
    'export default serverRegistry',
    '',
  ].join('\n')
}

function renderTypes(definitions: readonly DiscoveredDefinition[]): string {
  const interfaceByKind = {
    panel: 'PanelRegistry',
    resource: 'ResourceRegistry',
    page: 'PageRegistry',
    widget: 'WidgetRegistry',
    cluster: 'ClusterRegistry',
    'relation-manager': 'RelationManagerRegistry',
    plugin: 'PluginRegistry',
    import: 'ImportRegistry',
    export: 'ExportRegistry',
  } as const
  const sections = Object.entries(interfaceByKind).flatMap(([kind, interfaceName]) => {
    const matching = definitions.filter(definition => definition.kind === kind)
    return [
      `  interface ${interfaceName} {`,
      ...matching.map(definition => `    ${JSON.stringify(`${definition.panelId}:${definition.id}`)}: true`),
      '  }',
    ]
  })

  return [
    GENERATED_HEADER,
    '',
    "declare module '@holo-js/panels' {",
    ...sections,
    '}',
    '',
    'export {}',
    '',
  ].join('\n')
}

function renderJson(value: ClientManifestValue): string {
  return `${JSON.stringify(value, null, 2)}\n`
}

function joinedRoutePath(...values: readonly string[]): string {
  const segments = values.flatMap(value => value.split('/').filter(Boolean))
  return segments.length === 0 ? '/' : `/${segments.join('/')}`
}

function panelRoutesValue(definitions: readonly DiscoveredDefinition[]): ClientManifestValue {
  const routes = definitions.filter(definition => definition.kind === 'panel').flatMap((definition) => {
    const server = definition.server && typeof definition.server === 'object' ? definition.server : null
    const configured = server && Array.isArray(Reflect.get(server, 'routes')) ? Reflect.get(server, 'routes') as readonly object[] : []
    const panelPath = typeof definition.client.path === 'string' ? definition.client.path : `/${definition.panelId}`
    const routeDomain = server && typeof Reflect.get(server, 'routeDomain') === 'string' ? String(Reflect.get(server, 'routeDomain')) : null
    const routePrefix = server && typeof Reflect.get(server, 'routePrefix') === 'string' ? String(Reflect.get(server, 'routePrefix')) : ''
    return configured.map((route) => {
      const method = Reflect.get(route, 'method')
      const path = Reflect.get(route, 'path')
      const scope = Reflect.get(route, 'scope')
      if (typeof method !== 'string' || typeof path !== 'string' || typeof scope !== 'string') throw new TypeError('Compiled panel routes require method, path, and scope metadata')
      const tenantScoped = scope === 'tenant' || scope === 'authenticated-tenant'
      const source = tenantScoped && !routeDomain
        ? joinedRoutePath(panelPath, routePrefix, ':tenant', path)
        : joinedRoutePath(panelPath, path)
      return { domain: tenantScoped ? routeDomain : null, method, panelId: definition.panelId, scope, source }
    })
  })
  return { routes, version: 1 }
}

export function renderPanelArtifacts(
  definitions: readonly DiscoveredDefinition[],
): readonly GeneratedPanelArtifact[] {
  const clientManifest = definitions.map(publicValue)
  const clientComponents = definitions
    .filter(definition => typeof definition.client.component === 'string')
    .map(definition => ({
      key: definition.client.component ?? null,
      panelId: definition.panelId,
      definitionId: definition.id,
      kind: definition.kind,
    }))
  const navigation = definitions.flatMap(definition => definition.navigationKeys.map(key => ({
    key,
    panelId: definition.panelId,
    definitionId: definition.id,
  })))
  const permissions = definitions.flatMap(definition => definition.permissionKeys.map(key => ({
    key,
    panelId: definition.panelId,
    definitionId: definition.id,
  })))
  const frameworkArtifacts = { version: 1, panels: definitions.filter(definition => definition.kind === 'panel').map(publicValue) }
  const contentsByName: Record<(typeof artifactNames)[number], string> = {
    'panels.ts': renderModule('panels', byKind(definitions, 'panel')),
    'server-registry.ts': renderServerRegistry(definitions),
    'client-manifest.ts': renderModule('clientManifest', clientManifest),
    'client-components.ts': renderModule('clientComponents', clientComponents),
    'resources.ts': renderModule('resources', byKind(definitions, 'resource')),
    'pages.ts': renderModule('pages', byKind(definitions, 'page')),
    'widgets.ts': renderModule('widgets', byKind(definitions, 'widget')),
    'clusters.ts': renderModule('clusters', byKind(definitions, 'cluster')),
    'navigation.ts': renderModule('navigation', navigation),
    'permissions.ts': renderModule('permissions', permissions),
    'types.d.ts': renderTypes(definitions),
    'framework-artifacts.json': renderJson(frameworkArtifacts),
    'panel-routes.json': renderJson(panelRoutesValue(definitions)),
    'registry.json': renderJson(registryValue(definitions)),
  }

  return artifactNames.map(name => ({
    path: name,
    contents: contentsByName[name],
  }))
}

export { GENERATED_HEADER, artifactNames as PANEL_ARTIFACT_NAMES }
